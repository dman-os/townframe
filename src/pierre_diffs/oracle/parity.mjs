// Parity matrix generator. Maps every upstream file (parity/upstream_files.psv:
// `@pierre/diffs` src/ and test/ at diffs-v1.6.4 and the jsdiff 9.0.0 libesm
// files) to a status through the ordered rules in parity/rules.psv, then writes
// parity/matrix.psv (read by the Rust `parity` test) and PARITY.md.
//
//   node oracle/parity.mjs           regenerate
//   node oracle/parity.mjs --check   fail on an unmapped file, a rule that
//                                    matches nothing, or stale output
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const crateDir = join(here, "..");
const check = process.argv.includes("--check");
const STATUSES = ["PORTED", "REPLACED", "PENDING", "OUT", "DEFER"];

function readPsv(name) {
  return readFileSync(join(crateDir, name), "utf8")
    .split("\n")
    .filter((line) => line !== "" && !line.startsWith("#"))
    .map((line) => line.split("|"));
}

/** `*` matches any run of characters; `[..]` classes pass through. */
function globToRegex(pattern) {
  const body = pattern
    .split(/(\*|\[[^\]]*\])/)
    .map((part) => {
      if (part === "*") return ".*";
      if (part.startsWith("[")) return part;
      return part.replace(/[.+?^${}()|\\]/g, "\\$&");
    })
    .join("");
  return new RegExp(`^${body}$`);
}

const files = readPsv("parity/upstream_files.psv").map(([path, loc]) => ({
  path,
  loc: Number(loc),
}));
const rules = readPsv("parity/rules.psv").map(
  ([pattern, status, slice, rust, note]) => {
    if (!STATUSES.includes(status)) {
      throw new Error(`rule ${pattern}: unknown status ${status}`);
    }
    return {
      pattern,
      status,
      slice,
      rust,
      note: note ?? "",
      regex: globToRegex(pattern),
      hits: 0,
    };
  },
);

const problems = [];
const matrix = [];
for (const file of files) {
  const rule = rules.find((candidate) => candidate.regex.test(file.path));
  if (!rule) {
    problems.push(`unmapped upstream file: ${file.path}`);
    continue;
  }
  rule.hits += 1;
  matrix.push({ ...file, ...rule });
}
for (const rule of rules) {
  if (rule.hits === 0) {
    problems.push(`rule matches no file: ${rule.pattern}`);
  }
}

const psv = matrix
  .map(
    (row) =>
      `${row.path}|${row.loc}|${row.status}|${row.slice}|${row.rust}|${row.note}\n`,
  )
  .join("");

const counts = {};
for (const row of matrix) {
  const key = `${row.status}`;
  counts[key] = counts[key] ?? { files: 0, loc: 0 };
  counts[key].files += 1;
  counts[key].loc += row.loc;
}
let markdown =
  "# Parity matrix\n\n" +
  "Generated by `node oracle/parity.mjs` from `parity/upstream_files.psv` and `parity/rules.psv`; do not edit by hand.\n" +
  "Upstream: `@pierre/diffs` 1.6.4 (tag `diffs-v1.6.4`, commit `75e00805b44e193c0fb235c1bd9d7fadfa06acf6`) and `diff` 9.0.0 (`libesm`).\n" +
  "The Rust `parity` test checks that every `PORTED` row names existing files that carry a matching upstream header (`REPLACED` rows cite the Rust file standing in for the upstream one), and that every file with a `Ported from` header is listed here.\n\n" +
  "| status | files | upstream LOC |\n|---|---:|---:|\n";
for (const status of STATUSES) {
  const entry = counts[status] ?? { files: 0, loc: 0 };
  markdown += `| ${status} | ${entry.files} | ${entry.loc} |\n`;
}
markdown +=
  "\n| upstream file | LOC | status | slice | Rust location | note |\n|---|---:|---|---|---|---|\n";
for (const row of matrix) {
  const rust = row.rust
    ? row.rust
        .split(";")
        .map((path) => `\`${path}\``)
        .join(", ")
    : "";
  markdown += `| \`${row.path}\` | ${row.loc} | ${row.status} | ${row.slice} | ${rust} | ${row.note.replaceAll("|", "\\|")} |\n`;
}

// Upstream assertions that depend on jsdiff's exact output (or on a fixture
// absent from the extracted tree) and were converted to invariants; kept by
// hand in parity/divergences.psv as `test file|test title|conversion`.
const divergences = readPsv("parity/divergences.psv");
markdown += `\n## Assertions converted to invariants (${divergences.length})\n\n| upstream test | title | conversion |\n|---|---|---|\n`;
for (const [testFile, title, conversion] of divergences) {
  markdown += `| \`${testFile}\` | ${title} | ${conversion} |\n`;
}

// Upstream members and branches the port leaves out on purpose (caches, the
// worker pool, the edit session, ...), kept by hand in parity/dropped.psv as
// `upstream file|dropped member|reason`.
const dropped = readPsv("parity/dropped.psv");
markdown += `\n## Dropped branches (${dropped.length})\n\n| upstream file | dropped | reason |\n|---|---|---|\n`;
for (const [file, member, reason] of dropped) {
  markdown += `| \`${file}\` | ${member.replaceAll("|", "\\|")} | ${reason.replaceAll("|", "\\|")} |\n`;
}

const outputs = { "parity/matrix.psv": psv, "PARITY.md": markdown };
for (const [name, text] of Object.entries(outputs)) {
  const path = join(crateDir, name);
  if (check) {
    let current = "";
    try {
      current = readFileSync(path, "utf8");
    } catch {
      // missing counts as stale
    }
    if (current !== text) {
      problems.push(`stale output: ${name}`);
    }
  } else {
    writeFileSync(path, text);
  }
}
if (problems.length > 0) {
  console.error(problems.join("\n"));
  process.exit(1);
}
console.log(
  STATUSES.map((status) => `${status}=${counts[status]?.files ?? 0}`).join(" "),
);
