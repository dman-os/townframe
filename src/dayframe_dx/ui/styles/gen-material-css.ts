#!/usr/bin/env -S pnpm exec tsx

/**
 * Generate material.css and material-tokens.ts from material-theme.json for an RN app.
 * Usage: pnpm exec tsx x/gen-material-css.ts <app-dir> [theme-output-name]
 * Example: pnpm exec tsx x/gen-material-css.ts src/sysadmin
 *          pnpm exec tsx x/gen-material-css.ts src/shopadmin high-contrast
 *
 * Reads <app-dir>/src/material-theme.json (or <app-dir>/src/themes/<theme-output-name>/material-theme.json
 * when theme-output-name is given), writes material.css and material-tokens.ts.
 * When using theme-output-name, writes under src/themes/<theme-output-name>/ so an app can have multiple material styles.
 */

import { access, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import Color from "colorjs.io";
import { z } from "zod";

const schema = z.object({
  schemes: z.record(z.string(), z.record(z.string(), z.string())),
  palettes: z.record(z.string(), z.record(z.string(), z.string())),
});

function camelToKebab(input: string) {
  return input
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .replace(/_/g, "-")
    .toLowerCase();
}

function toOklch(color: string) {
  const converted = new Color(color).to("oklch");
  const l = Number((converted.coords[0] * 100).toFixed(3));
  const c = Number(converted.coords[1].toFixed(3));
  const rawHue = converted.coords[2];
  const h = Number((Number.isFinite(rawHue) ? rawHue : 0).toFixed(3));
  return `oklch(${l}% ${c} ${h})`;
}

function toHex(color: string): string {
  return new Color(color).toString({ format: "hex" });
}

const semanticMap = {
  background: "background",
  foreground: "on-background",
  card: "surface-container-low",
  "card-foreground": "on-surface",
  popover: "surface-container",
  "popover-foreground": "on-surface",
  primary: "primary",
  "primary-foreground": "on-primary",
  secondary: "secondary",
  "secondary-foreground": "on-secondary",
  muted: "surface-variant",
  "muted-foreground": "on-surface-variant",
  accent: "secondary-container",
  "accent-foreground": "on-secondary-container",
  destructive: "error",
  "destructive-foreground": "on-error",
  border: "outline-variant",
  input: "outline",
  ring: "primary",
} as const;

async function exists(filePath: string) {
  try {
    await access(filePath);
    return true;
  } catch {
    return false;
  }
}

async function main() {
  const appDir = process.argv[2];
  const themeOutputName = process.argv[3];
  if (!appDir) {
    console.error(
      "Usage: pnpm exec tsx x/gen-material-css.ts <app-dir> [theme-output-name]",
    );
    console.error("Example: pnpm exec tsx x/gen-material-css.ts src/sysadmin");
    console.error(
      "         pnpm exec tsx x/gen-material-css.ts src/shopadmin high-contrast",
    );
    process.exit(1);
  }
  const baseDir = path.resolve(process.cwd(), appDir);
  const srcDir = path.join(baseDir, "src");
  const hasSrcTheme = await exists(path.join(srcDir, "material-theme.json"));
  const baseThemeDir = hasSrcTheme ? srcDir : baseDir;

  const outDir = themeOutputName
    ? path.join(srcDir, "themes", themeOutputName)
    : baseThemeDir;
  const jsonPath = path.join(outDir, "material-theme.json");
  const outCssPath = path.join(outDir, "material.css");
  const outTokensPath = path.join(outDir, "material-tokens.ts");

  const raw = await readFile(jsonPath, "utf8");
  const parsed = schema.parse(JSON.parse(raw));

  const paletteLines: string[] = [];
  for (const [paletteName, palette] of Object.entries(parsed.palettes)) {
    for (const [step, value] of Object.entries(palette)) {
      const tokenName = `${camelToKebab(paletteName)}-${step.padStart(2, "0")}`;
      paletteLines.push(`  --color-${tokenName}: ${toOklch(value)};`);
    }
  }

  const allSchemeKeys = new Set<string>();
  const schemeVarBlocks: string[] = [];
  for (const [schemeName, scheme] of Object.entries(parsed.schemes)) {
    const lines: string[] = [];
    for (const [name, value] of Object.entries(scheme)) {
      const tokenName = camelToKebab(name);
      allSchemeKeys.add(tokenName);
      lines.push(`  --scheme-color-${tokenName}: ${toOklch(value)};`);
    }
    const selector =
      schemeName === "light" ? ":root,\n.light" : `.${schemeName}`;
    schemeVarBlocks.push(`${selector} {\n${lines.join("\n")}\n}`);
  }

  const semanticTokenSet = new Set(Object.keys(semanticMap));
  const schemeColorAliases = [...allSchemeKeys]
    .filter((key) => !semanticTokenSet.has(key))
    .sort()
    .map((key) => `  --color-${key}: var(--scheme-color-${key});`);

  const semanticLines = Object.entries(semanticMap).map(
    ([semantic, source]) =>
      `  --color-${semantic}: var(--scheme-color-${source});`,
  );

  const css = `/* @generated by x/gen-material-css.ts */

/* Palette colors (scheme-agnostic) */
@theme {
${paletteLines.join("\n")}
}

/* Scheme colors + app semantic aliases */
@theme inline {
${schemeColorAliases.join("\n")}
${semanticLines.join("\n")}
}

${schemeVarBlocks.join("\n\n")}
`;

  await writeFile(outCssPath, css, "utf8");

  const schemeNames = Object.keys(parsed.schemes);

  function schemeVarName(schemeName: string): string {
    return schemeName.replace(/-([a-z])/g, (_, c: string) => c.toUpperCase());
  }

  const schemeConstBlocks: string[] = [];
  for (const schemeName of schemeNames) {
    const scheme = parsed.schemes[schemeName];
    const entries: string[] = [];
    const map: Record<string, string> = {};
    for (const [name, value] of Object.entries(scheme)) {
      const tokenName = camelToKebab(name);
      map[tokenName] = toHex(value);
    }
    for (const [semantic, source] of Object.entries(semanticMap)) {
      if (map[source] != null) {
        map[semantic] = map[source];
      }
    }
    for (const [key, value] of Object.entries(map)) {
      entries.push(`  "${key}": "${value}",`);
    }
    schemeConstBlocks.push(
      `const ${schemeVarName(schemeName)}: Record<string, string> = {\n${entries.join("\n")}\n};`,
    );
  }

  const schemeIdUnion = schemeNames.map((s) => `"${s}"`).join(" | ");
  const schemesEntries = schemeNames
    .map((s) => `  "${s}": ${schemeVarName(s)},`)
    .join("\n");

  const tsContent = `/* @generated by x/gen-material-css.ts */

export type SchemeId = ${schemeIdUnion};

${schemeConstBlocks.join("\n\n")}

const schemes: Record<SchemeId, Record<string, string>> = {
${schemesEntries}
};

export function getMaterialColors(scheme: SchemeId): Record<string, string> {
  return schemes[scheme] ?? schemes.light;
}
`;

  await writeFile(outTokensPath, tsContent, "utf8");
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
