#[derive(Debug, Clone, Serialize)]
pub struct ApiImpactReport {
    pub package: String,
    pub snapshot_path: String,
    pub added_items: Vec<String>,
    pub removed_items: Vec<String>,
    pub exposed_external_crates: BTreeSet<String>,
    pub newly_exposed_external_crates: BTreeSet<String>,
    pub affected_consumers: BTreeSet<String>,
    pub required_checks: Vec<Vec<String>>,
}

#[derive(Debug, Clone, Serialize)]
pub struct OverlapReport {
    pub compared_worktrees: Vec<String>,
    pub symbol_overlaps: BTreeMap<String, Vec<String>>,
    pub migration_stream_overlaps: BTreeMap<String, Vec<String>>,
    pub api_contract_overlaps: BTreeMap<String, Vec<String>>,
}

pub fn pilot_packages(repo: &Repository) -> Vec<String> {
    let mut result = Vec::new();
    for name in repo.packages.keys() {
        if let Ok(path) = repo.policy_path(name)
            && path.is_file()
            && let Ok(text) = std::fs::read_to_string(&path)
            && let Ok(policy) = toml::from_str::<Policy>(&text)
            && policy.api.is_some()
        {
            result.push(name.clone());
        }
    }
    result.sort();
    result
}

pub fn api(
    root: &Path,
    package_name: Option<&str>,
    all: bool,
    accept: bool,
    json: bool,
) -> Res<bool> {
    let repo = Repository::load(root)?;
    let targets: Vec<String> = if all || package_name.is_none() {
        pilot_packages(&repo)
    } else if let Some(pkg) = package_name {
        vec![pkg.to_string()]
    } else {
        Vec::new()
    };
    eyre::ensure!(
        !targets.is_empty(),
        "no packages configured with [api] in guardrails.toml"
    );

    let mut all_ok = true;
    let mut reports = Vec::new();
    for name in &targets {
        let package = repo
            .packages
            .get(name)
            .ok_or_else(|| eyre::eyre!("unknown package `{name}`"))?;
        let policy_path = repo.policy_path(name)?;
        let policy: Policy = toml::from_str(
            &std::fs::read_to_string(&policy_path)
                .wrap_err_with(|| format!("reading {}", policy_path.display()))?,
        )?;
        let configuration = policy.api.as_ref().ok_or_else(|| {
            eyre::eyre!("package `{name}` has no [api] section in guardrails.toml")
        })?;
        eyre::ensure!(
            !configuration.target.is_empty(),
            "API configuration for `{name}` must specify a target"
        );

        let (items, exposed_external) = extract_crate_public_api(&repo, package)?;
        eyre::ensure!(
            !items.is_empty(),
            "extracted public API for `{name}` is empty"
        );

        let mut header = String::new();
        header.push_str(&format!(
            "# @generated by `cargo x guardrails api --package {name} --bless`\n"
        ));
        header.push_str(&format!("# package: {name}\n"));
        header.push_str(&format!(
            "# configuration: {}\n",
            serde_json::to_string(configuration)?
        ));
        let exposed_list: Vec<&str> = exposed_external.iter().map(String::as_str).collect();
        header.push_str(&format!(
            "# exposed_external_crates: [{}]\n\n",
            exposed_list.join(", ")
        ));
        let snapshot = format!("{header}{}\n", items.join("\n"));

        let crate_dir = package
            .manifest_path
            .parent()
            .ok_or_eyre("manifest parent")?;
        let snapshot_path = crate_dir.join("public-api.txt");
        let rel_snapshot = relative(root, &snapshot_path)?;

        if accept {
            std::fs::write(&snapshot_path, &snapshot)?;
            if !json {
                println!(
                    "api: wrote {} ({} public items, {} exposed external crates)",
                    rel_snapshot,
                    items.len(),
                    exposed_external.len()
                );
            }
            continue;
        }

        let expected = match std::fs::read_to_string(&snapshot_path) {
            Ok(text) => text,
            Err(_) => {
                all_ok = false;
                let consumers = repo.reverse_dependencies(name);
                let required_checks = consumer_check_commands(&consumers);
                reports.push(ApiImpactReport {
                    package: name.clone(),
                    snapshot_path: rel_snapshot.clone(),
                    added_items: items.clone(),
                    removed_items: Vec::new(),
                    exposed_external_crates: exposed_external.clone(),
                    newly_exposed_external_crates: exposed_external.clone(),
                    affected_consumers: consumers,
                    required_checks,
                });
                continue;
            }
        };

        if expected != snapshot {
            all_ok = false;
            let expected_items: BTreeSet<String> = expected
                .lines()
                .filter(|line| !line.starts_with('#') && !line.trim().is_empty())
                .map(String::from)
                .collect();
            let current_items: BTreeSet<String> = items.iter().cloned().collect();
            let added_items: Vec<String> =
                current_items.difference(&expected_items).cloned().collect();
            let removed_items: Vec<String> =
                expected_items.difference(&current_items).cloned().collect();
            let old_exposed = parse_exposed_header(&expected);
            let newly_exposed: BTreeSet<String> =
                exposed_external.difference(&old_exposed).cloned().collect();
            let consumers = repo.reverse_dependencies(name);
            let required_checks = consumer_check_commands(&consumers);
            reports.push(ApiImpactReport {
                package: name.clone(),
                snapshot_path: rel_snapshot,
                added_items,
                removed_items,
                exposed_external_crates: exposed_external,
                newly_exposed_external_crates: newly_exposed,
                affected_consumers: consumers,
                required_checks,
            });
        } else if !json {
            println!("api: {} ok ({} public items)", rel_snapshot, items.len());
        }
    }

    print_api_reports(&reports, json)?;
    Ok(all_ok)
}

fn print_api_reports(reports: &[ApiImpactReport], json: bool) -> Res<()> {
    if json {
        println!("{}", serde_json::to_string_pretty(reports)?);
        return Ok(());
    }
    for report in reports {
        eprintln!(
            "ERROR_PUBLIC_API [{}]: {} changed (+{} added, -{} removed)",
            report.package,
            report.snapshot_path,
            report.added_items.len(),
            report.removed_items.len()
        );
        for item in report.added_items.iter().take(15) {
            eprintln!("  + {item}");
        }
        for item in report.removed_items.iter().take(15) {
            eprintln!("  - {item}");
        }
        if !report.newly_exposed_external_crates.is_empty() {
            eprintln!(
                "  newly exposed external crates: {:?}",
                report.newly_exposed_external_crates
            );
        }
        if !report.affected_consumers.is_empty() {
            eprintln!("  affected consumers: {:?}", report.affected_consumers);
        }
        eprintln!(
            "  to accept intentional contract change: `cargo x guardrails api --package {} --bless`",
            report.package
        );
    }
    Ok(())
}

fn parse_exposed_header(snapshot: &str) -> BTreeSet<String> {
    for line in snapshot.lines().take(10) {
        if let Some(rest) = line.strip_prefix("# exposed_external_crates: [")
            && let Some(inner) = rest.strip_suffix(']')
        {
            return inner
                .split(',')
                .map(str::trim)
                .filter(|item| !item.is_empty())
                .map(String::from)
                .collect();
        }
    }
    BTreeSet::new()
}

fn consumer_check_commands(consumers: &BTreeSet<String>) -> Vec<Vec<String>> {
    let mut commands = Vec::new();
    for pkg in consumers {
        commands.push(vec![
            "cargo".into(),
            "clippy".into(),
            "--locked".into(),
            "-p".into(),
            pkg.clone(),
            "--all-targets".into(),
            "--all-features".into(),
        ]);
        commands.push(vec![
            "cargo".into(),
            "nextest".into(),
            "run".into(),
            "--locked".into(),
            "-p".into(),
            pkg.clone(),
        ]);
    }
    commands
}

pub fn extract_crate_public_api(
    repo: &Repository,
    package: &Package,
) -> Res<(Vec<String>, BTreeSet<String>)> {
    let crate_dir = package
        .manifest_path
        .parent()
        .ok_or_eyre("manifest parent")?;
    let entry = if crate_dir.join("lib.rs").is_file() {
        crate_dir.join("lib.rs")
    } else if crate_dir.join("src/lib.rs").is_file() {
        crate_dir.join("src/lib.rs")
    } else {
        crate_dir.join("main.rs")
    };
    let external_deps: BTreeSet<String> = package
        .dependencies
        .iter()
        .filter(|dep| !repo.packages.contains_key(&dep.name))
        .map(|dep| dep.name.replace('-', "_"))
        .collect();

    let mut items = BTreeSet::new();
    let mut exposed_external = BTreeSet::new();
    let mut visited = BTreeSet::new();
    walk_public_module(
        &entry,
        &package.name,
        &external_deps,
        &mut visited,
        &mut items,
        &mut exposed_external,
    )?;
    Ok((items.into_iter().collect(), exposed_external))
}

fn walk_public_module(
    file_path: &Path,
    mod_prefix: &str,
    external_deps: &BTreeSet<String>,
    visited: &mut BTreeSet<PathBuf>,
    items: &mut BTreeSet<String>,
    exposed_external: &mut BTreeSet<String>,
) -> Res<()> {
    let canon = file_path
        .canonicalize()
        .unwrap_or_else(|_| file_path.to_path_buf());
    if !visited.insert(canon) {
        return Ok(());
    }
    let text = std::fs::read_to_string(file_path)
        .wrap_err_with(|| format!("reading {}", file_path.display()))?;
    let parsed = syn::parse_file(&text)
        .map_err(|err| eyre::eyre!("parsing {}: {err}", file_path.display()))?;
    let parent_dir = file_path.parent().ok_or_eyre("file parent")?;
    let file_stem = file_path
        .file_stem()
        .and_then(|stem| stem.to_str())
        .unwrap_or("");
    let child_search_dir = if matches!(file_stem, "lib" | "main" | "mod") {
        parent_dir.to_path_buf()
    } else {
        parent_dir.join(file_stem)
    };
    collect_public_items(
        &parsed.items,
        mod_prefix,
        &child_search_dir,
        external_deps,
        visited,
        items,
        exposed_external,
    )
}

fn is_pub(vis: &syn::Visibility) -> bool {
    matches!(vis, syn::Visibility::Public(_))
}

fn normalize_tokens(tokens: impl ToTokens) -> String {
    tokens
        .to_token_stream()
        .to_string()
        .split_whitespace()
        .collect::<Vec<_>>()
        .join(" ")
}

fn record_external_types(
    tokens: &proc_macro2::TokenStream,
    external_deps: &BTreeSet<String>,
    exposed: &mut BTreeSet<String>,
) {
    let mut iter = tokens.clone().into_iter().peekable();
    while let Some(tt) = iter.next() {
        match tt {
            proc_macro2::TokenTree::Ident(ident) => {
                let name = ident.to_string();
                if external_deps.contains(&name)
                    && let Some(proc_macro2::TokenTree::Punct(punct)) = iter.peek()
                    && punct.as_char() == ':'
                {
                    exposed.insert(name);
                }
            }
            proc_macro2::TokenTree::Group(group) => {
                record_external_types(&group.stream(), external_deps, exposed);
            }
            _ => {}
        }
    }
}

fn collect_public_items(
    ast_items: &[syn::Item],
    mod_prefix: &str,
    child_dir: &Path,
    external_deps: &BTreeSet<String>,
    visited: &mut BTreeSet<PathBuf>,
    items: &mut BTreeSet<String>,
    exposed_external: &mut BTreeSet<String>,
) -> Res<()> {
    for item in ast_items {
        if let syn::Item::Mod(item) = item
            && is_pub(&item.vis)
        {
            let sub_prefix = format!("{mod_prefix}::{}", item.ident);
            items.insert(format!("pub mod {sub_prefix}"));
            if let Some((_, content)) = &item.content {
                let inline_dir = child_dir.join(item.ident.to_string());
                collect_public_items(
                    content,
                    &sub_prefix,
                    &inline_dir,
                    external_deps,
                    visited,
                    items,
                    exposed_external,
                )?;
            } else {
                let candidate_file = child_dir.join(format!("{}.rs", item.ident));
                let candidate_mod = child_dir.join(item.ident.to_string()).join("mod.rs");
                if candidate_file.is_file() {
                    walk_public_module(
                        &candidate_file,
                        &sub_prefix,
                        external_deps,
                        visited,
                        items,
                        exposed_external,
                    )?;
                } else if candidate_mod.is_file() {
                    walk_public_module(
                        &candidate_mod,
                        &sub_prefix,
                        external_deps,
                        visited,
                        items,
                        exposed_external,
                    )?;
                }
            }
        } else {
            collect_public_leaf_item(item, mod_prefix, external_deps, items, exposed_external);
        }
    }
    Ok(())
}

fn collect_public_leaf_item(
    item: &syn::Item,
    mod_prefix: &str,
    external_deps: &BTreeSet<String>,
    items: &mut BTreeSet<String>,
    exposed_external: &mut BTreeSet<String>,
) {
    match item {
        syn::Item::Fn(item) if is_pub(&item.vis) => {
            let sig = normalize_tokens(&item.sig);
            record_external_types(&item.sig.to_token_stream(), external_deps, exposed_external);
            items.insert(format!("pub {mod_prefix}::{sig}"));
        }
        syn::Item::Struct(item) if is_pub(&item.vis) => {
            let generics = normalize_tokens(&item.generics);
            let where_clause = item
                .generics
                .where_clause
                .as_ref()
                .map(normalize_tokens)
                .unwrap_or_default();
            let mut fields = Vec::new();
            for (idx, field) in item.fields.iter().enumerate() {
                if is_pub(&field.vis) {
                    record_external_types(
                        &field.ty.to_token_stream(),
                        external_deps,
                        exposed_external,
                    );
                    let name = field
                        .ident
                        .as_ref()
                        .map(ToString::to_string)
                        .unwrap_or_else(|| idx.to_string());
                    fields.push(format!("{name}: {}", normalize_tokens(&field.ty)));
                }
            }
            items.insert(format!(
                "pub struct {mod_prefix}::{}{generics} {where_clause} {{ {} }}",
                item.ident,
                fields.join(", ")
            ));
        }
        syn::Item::Enum(item) if is_pub(&item.vis) => {
            let generics = normalize_tokens(&item.generics);
            let variants: Vec<String> = item
                .variants
                .iter()
                .map(|variant| {
                    record_external_types(
                        &variant.fields.to_token_stream(),
                        external_deps,
                        exposed_external,
                    );
                    normalize_tokens(variant)
                })
                .collect();
            items.insert(format!(
                "pub enum {mod_prefix}::{}{generics} {{ {} }}",
                item.ident,
                variants.join(", ")
            ));
        }
        syn::Item::Trait(item) if is_pub(&item.vis) => {
            let generics = normalize_tokens(&item.generics);
            let methods: Vec<String> = item
                .items
                .iter()
                .filter_map(|trait_item| match trait_item {
                    syn::TraitItem::Fn(method) => {
                        record_external_types(
                            &method.sig.to_token_stream(),
                            external_deps,
                            exposed_external,
                        );
                        Some(normalize_tokens(&method.sig))
                    }
                    syn::TraitItem::Type(assoc_ty) => Some(format!("type {}", assoc_ty.ident)),
                    syn::TraitItem::Const(assoc_const) => Some(format!(
                        "const {}: {}",
                        assoc_const.ident,
                        normalize_tokens(&assoc_const.ty)
                    )),
                    _ => None,
                })
                .collect();
            items.insert(format!(
                "pub trait {mod_prefix}::{}{generics} {{ {} }}",
                item.ident,
                methods.join("; ")
            ));
        }
        syn::Item::Type(item) if is_pub(&item.vis) => {
            record_external_types(&item.ty.to_token_stream(), external_deps, exposed_external);
            items.insert(format!(
                "pub type {mod_prefix}::{}{} = {}",
                item.ident,
                normalize_tokens(&item.generics),
                normalize_tokens(&item.ty)
            ));
        }
        syn::Item::Const(item) if is_pub(&item.vis) => {
            record_external_types(&item.ty.to_token_stream(), external_deps, exposed_external);
            items.insert(format!(
                "pub const {mod_prefix}::{}: {}",
                item.ident,
                normalize_tokens(&item.ty)
            ));
        }
        syn::Item::Static(item) if is_pub(&item.vis) => {
            record_external_types(&item.ty.to_token_stream(), external_deps, exposed_external);
            items.insert(format!(
                "pub static {mod_prefix}::{}: {}",
                item.ident,
                normalize_tokens(&item.ty)
            ));
        }
        syn::Item::Use(item) if is_pub(&item.vis) => {
            record_external_types(
                &item.tree.to_token_stream(),
                external_deps,
                exposed_external,
            );
            items.insert(format!(
                "pub use {mod_prefix}::{}",
                normalize_tokens(&item.tree)
            ));
        }
        syn::Item::Impl(item) => {
            let ty = normalize_tokens(&item.self_ty);
            if let Some((_, trait_path, _)) = &item.trait_ {
                let trait_str = normalize_tokens(trait_path);
                let unsafety = if item.unsafety.is_some() {
                    "unsafe "
                } else {
                    ""
                };
                items.insert(format!("{unsafety}impl {trait_str} for {mod_prefix}::{ty}"));
            } else {
                for impl_item in &item.items {
                    if let syn::ImplItem::Fn(method) = impl_item
                        && is_pub(&method.vis)
                    {
                        record_external_types(
                            &method.sig.to_token_stream(),
                            external_deps,
                            exposed_external,
                        );
                        items.insert(format!(
                            "pub impl {mod_prefix}::{ty}::{}",
                            normalize_tokens(&method.sig)
                        ));
                    }
                }
            }
        }
        _ => {}
    }
}

pub fn overlap(
    root: &Path,
    base: Option<&Path>,
    worktrees_dir: Option<&Path>,
    json: bool,
) -> Res<bool> {
    // Every worktree is diffed against one trunk checkout. Comparing siblings
    // against each other would report a branch's own edits as overlap with
    // whichever sibling happened to sort first.
    let base = match base {
        Some(dir) => dir.canonicalize()?,
        None => match std::env::var_os("TOWNFRAME_TRUNK_DIR") {
            Some(dir) => PathBuf::from(dir).canonicalize()?,
            None => eyre::bail!(
                "overlap needs a trunk checkout to diff against: pass --base <dir> or set TOWNFRAME_TRUNK_DIR"
            ),
        },
    };
    eyre::ensure!(
        base.join("Cargo.toml").is_file(),
        "base {} is not a workspace checkout",
        base.display()
    );
    let parent = match worktrees_dir {
        Some(dir) => dir.to_path_buf(),
        None => root
            .parent()
            .ok_or_eyre("workspace root has no parent directory")?
            .to_path_buf(),
    };
    let mut worktrees = vec![root.to_path_buf()];
    if parent.is_dir() {
        for entry in std::fs::read_dir(&parent)? {
            let path = entry?.path();
            let canonical = path.canonicalize().unwrap_or_else(|_| path.clone());
            if path.is_dir()
                && path != root
                && canonical != base
                && path.join("Cargo.toml").is_file()
            {
                worktrees.push(path);
            }
        }
    }
    worktrees.sort();

    let mut symbol_touches: BTreeMap<String, Vec<String>> = BTreeMap::new();
    let mut migration_touches: BTreeMap<String, Vec<String>> = BTreeMap::new();
    let mut api_touches: BTreeMap<String, Vec<String>> = BTreeMap::new();
    let mut compared_names = Vec::new();

    {
        for worktree in worktrees {
            let label = worktree
                .file_name()
                .map(|name| name.to_string_lossy().to_string())
                .unwrap_or_else(|| worktree.display().to_string());
            compared_names.push(label.clone());
            for file in files(&worktree.join("src"))? {
                let rel = relative(&worktree, &file)?;
                let base_file = base.join(&rel);
                if file.extension().is_some_and(|ext| ext == "rs") {
                    let cur_text = std::fs::read_to_string(&file).unwrap_or_default();
                    let base_text = std::fs::read_to_string(&base_file).unwrap_or_default();
                    if cur_text != base_text {
                        for sym in changed_symbols(&base_text, &cur_text) {
                            symbol_touches
                                .entry(format!("{rel}::{sym}"))
                                .or_default()
                                .push(label.clone());
                        }
                    }
                } else if file.extension().is_some_and(|ext| ext == "sql")
                    && file
                        .parent()
                        .and_then(Path::file_name)
                        .is_some_and(|dir_name| dir_name == "migrations")
                {
                    let cur_bytes = std::fs::read(&file).unwrap_or_default();
                    let base_bytes = std::fs::read(&base_file).unwrap_or_default();
                    if cur_bytes != base_bytes {
                        let stream = file
                            .parent()
                            .and_then(|parent_path| parent_path.strip_prefix(&worktree).ok())
                            .map(|rel_path| rel_path.display().to_string())
                            .unwrap_or(rel);
                        migration_touches
                            .entry(stream)
                            .or_default()
                            .push(label.clone());
                    }
                } else if file.file_name().and_then(|file_name| file_name.to_str())
                    == Some("public-api.txt")
                {
                    let cur_text = std::fs::read_to_string(&file).unwrap_or_default();
                    let base_text = std::fs::read_to_string(&base_file).unwrap_or_default();
                    if cur_text != base_text {
                        api_touches.entry(rel).or_default().push(label.clone());
                    }
                }
            }
        }
    }

    symbol_touches.retain(|_, owners| {
        owners.sort();
        owners.dedup();
        owners.len() > 1
    });
    migration_touches.retain(|_, owners| {
        owners.sort();
        owners.dedup();
        owners.len() > 1
    });
    api_touches.retain(|_, owners| {
        owners.sort();
        owners.dedup();
        owners.len() > 1
    });

    let report = OverlapReport {
        compared_worktrees: compared_names,
        symbol_overlaps: symbol_touches,
        migration_stream_overlaps: migration_touches,
        api_contract_overlaps: api_touches,
    };

    if json {
        println!("{}", serde_json::to_string_pretty(&report)?);
    } else {
        println!(
            "overlap: compared {} worktree(s); {} symbol overlap(s), {} migration overlap(s), {} API contract overlap(s)",
            report.compared_worktrees.len(),
            report.symbol_overlaps.len(),
            report.migration_stream_overlaps.len(),
            report.api_contract_overlaps.len()
        );
        for (sym, trees) in &report.symbol_overlaps {
            println!("  SYMBOL {sym}: {:?}", trees);
        }
        for (stream, trees) in &report.migration_stream_overlaps {
            println!("  MIGRATION {stream}: {:?}", trees);
        }
        for (api, trees) in &report.api_contract_overlaps {
            println!("  API {api}: {:?}", trees);
        }
    }
    Ok(true)
}
